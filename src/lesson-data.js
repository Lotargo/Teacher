export function checkNumber(task, answer, operation) {
  if (typeof answer !== 'string' || answer.trim() === '') return { ok: false, message: 'Сначала укажи количество. Можно воспользоваться кнопками − и +.' };
  const value = Number(answer);
  if (!Number.isInteger(value) || value < 0 || value > 20) return { ok: false, message: 'В этом примере укажи целое количество от 0 до 20.' };
  if (task.needsOperation && operation !== '-') return { ok: false, message: 'Ты ищешь, сколько было до добавления. Как отменить добавление: прибавить ещё раз или убрать добавленное?' };
  if (value === task.answer) return { ok: true, message: task.success };
  if (task.id === 'add') return { ok: false, message: 'Нужно посчитать и старые, и новые яблоки вместе. Попробуй пересчитать обе группы или открыть подсказку.' };
  return { ok: false, message: 'Проверим догадку: ' + value + ' + ' + (task.id === 'transfer' ? 4 : 3) + ' = ' + (value + (task.id === 'transfer' ? 4 : 3)) + '. По условию должно быть ' + (task.id === 'transfer' ? 10 : 8) + '. Пересмотри первоначальное количество.' };
}
